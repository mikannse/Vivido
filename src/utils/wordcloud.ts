const CHINESE_RUN = /[一-龥]+/g;

// 字长权重：多字词更可能承载生活主题，给予更高排序权重。
const lengthWeight = (len: number): number => {
  if (len >= 4) return 2.0;
  if (len === 3) return 1.6;
  return 1.0; // 2 字
};

const MIN_LEN = 2;
const MAX_LEN = 4;

/**
 * 候选词的计数结构：分离原始频次与加权排序分。
 * - raw：词实际出现的次数（用于分级，决定颜色/大小）
 * - weighted：字长加权后的分数（用于排序，仅排序用途）
 */
export interface WordCount {
  raw: number;
  weighted: number;
}

/**
 * 判断词是否以动词前缀开头 → 极大概是动词短语，应过滤。
 */
const isVerbPrefix = (word: string): boolean => {
  if (word.length === 0) return false;
  // 检查单字动词前缀
  if (VERB_PREFIX_1.has(word[0])) return true;
  // 检查双字动词前缀
  if (word.length >= 2 && VERB_PREFIX_2.has(word.slice(0, 2))) return true;
  return false;
};

/**
 * 判断词是否以语气词结尾 → 碎片词，应过滤。
 */
const hasParticleSuffix = (word: string): boolean => {
  if (word.length === 0) return false;
  return PARTICLE_SUFFIX.has(word[word.length - 1]);
};

/**
 * 判断词是否以名词后缀结尾 → 提升加权分。
 */
const hasNounSuffix = (word: string): boolean => {
  if (word.length < 3) return false; // 1 字修饰 + 2 字后缀 = 3 字即可（如"新公司"）
  return NOUN_SUFFIXES.has(word.slice(-2));
};

/**
 * 从一段文本累加加权词频到给定 map。
 * 返回的结构体同时追踪原始频次（raw）和加权分（weighted），
 * 便于下游分别用于分级和排序。
 */
export const accumulateWordFrequency = (
  text: string,
  wordCount: Map<string, WordCount>
): void => {
  const runs = text.match(CHINESE_RUN);
  if (!runs) return;

  for (const run of runs) {
    // 以虚词字符为分隔，切出内容块
    let chunk = '';
    const flush = () => {
      if (chunk.length >= MIN_LEN) {
        emitChunk(chunk, wordCount);
      }
      chunk = '';
    };

    for (const ch of run) {
      if (FUNCTION_CHARS.has(ch)) {
        flush();
      } else {
        chunk += ch;
      }
    }
    flush();
  }
};

const emitChunk = (chunk: string, wordCount: Map<string, WordCount>): void => {
  // 仅接受虚词字符自然切出的 2–4 字块。超过 4 字的块（整句粘连）不提取子串，
  // 因为任何滑动窗口都会产生"本来想学""来想学日"式噪声——零依赖分词做不到精准。
  // 这类词若真有主题价值，会在其他上下文中作为 2–4 字块自然出现。
  if (chunk.length < MIN_LEN || chunk.length > MAX_LEN) return;

  // 动词前缀过滤 —— 词以"想/要/会/能"或"开始/希望"开头 → 动词短语，不显示
  if (isVerbPrefix(chunk)) return;

  // 语气词后缀过滤 —— 词以"啥/吗/吧/呢"结尾 → 碎片词，不显示
  if (hasParticleSuffix(chunk)) return;

  addWord(chunk, wordCount);
};

const addWord = (word: string, wordCount: Map<string, WordCount>): void => {
  if (STOP_WORDS.has(word)) return;

  const existing = wordCount.get(word);
  const weighted = lengthWeight(word.length) * (hasNounSuffix(word) ? 1.5 : 1.0);

  if (existing) {
    existing.raw += 1;
    existing.weighted += weighted;
  } else {
    wordCount.set(word, { raw: 1, weighted });
  }
};
